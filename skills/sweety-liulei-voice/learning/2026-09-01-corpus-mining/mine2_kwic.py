PAT_SPECIAL = {
    "波浪号~": re.compile(r"[~～]"),
    "省略号……": re.compile(r"…|\.{3,}|。{2,}"),
    "叹号连发!!": re.compile(r"[!！]{2,}"),
    "颜文字^_^": re.compile(r"\^_\^|:\)|T_T|=_="),
    "括号补充（…）": re.compile(r"[（(][^）)]{4,}[）)]"),
    "问号？": re.compile(r"[?？]"),
    "重复强调(叠词)": re.compile(r"(很快的很快|终于终于|但是，但是|一定要.{0,6}一定要|至少至少)"),
    "自问自答(？…因为/答)": re.compile(r"[?？][^?？]{0,4}(因为|答案|其实|很简单)"),
    "不是A而是B": re.compile(r"不是.{1,18}而是"),
    "要么A要么B": re.compile(r"要么.{1,18}要么"),
    "先X再Y": re.compile(r"先.{1,12}[，,]?再"),
    "的话(假设)": re.compile(r"的话[，,。]"),
}

def main():
    w = open(os.path.join(OUT, "kwic_report.txt"), "w", encoding="utf-8")
    reg_count = collections.Counter(r for r, f, s in sents)
    w.write(f"sentences: {dict(reg_count)}\n")

    # rhythm metrics per register
    for reg in ("tech", "personal"):
        ss = [s for r, f, s in sents if r == reg]
        lens = [len(s) for s in ss]
        commas = [s.count("，") for s in ss]
        long80 = sum(1 for L in lens if L >= 80)
        long120 = sum(1 for L in lens if L >= 120)
        w.write(f"\n[{reg}] sents={len(ss)} avg_len={sum(lens)/len(ss):.0f} avg_commas={sum(commas)/len(ss):.1f} "
                f">=80char={long80*100//len(ss)}% >=120char={long120*100//len(ss)}% "
                f"maxcommas={max(commas)}\n")

    # special patterns
    w.write("\n== SPECIAL PATTERNS ==\n")
    for name, pat in PAT_SPECIAL.items():
        hits = [(r, f, s) for r, f, s in sents if pat.search(s)]
        w.write(f"\n### {name}: {len(hits)} sents\n")
        for r, f, s in hits[:4]:
            w.write(f"  [{r}] {s[:110]}\n")

    # candidate counts + KWIC
    for group, words in GROUPS.items():
        w.write(f"\n\n======== {group} ========\n")
        rows = []
        for word in words:
            hits = [(r, f, s) for r, f, s in sents if word in s]
            rows.append((len(hits), word, hits))
        rows.sort(reverse=True)
        for c, word, hits in rows:
            if c == 0:
                w.write(f"{word}\t0\n"); continue
            tech = sum(1 for r, _, _ in hits if r == "tech")
            w.write(f"{word}\t{c}\t(tech {tech} / personal {c-tech})\n")
            for r, f, s in hits[:2]:
                frag = s
                i = frag.find(word)
                lo, hi = max(0, i-40), min(len(frag), i+len(word)+50)
                w.write(f"    [{r}] …{frag[lo:hi]}…\n")
    w.close()
    print("kwic_report.txt written")

main()
